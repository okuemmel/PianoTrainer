"""Generate deterministic flash-resident web assets; samples remain optional in LittleFS."""
import gzip
from pathlib import Path


def assets(data):
    return [("/" + path.relative_to(data).as_posix(),
             gzip.compress(path.read_bytes(), compresslevel=9, mtime=0))
            for path in sorted(data.rglob("*"))
            if path.is_file() and not path.name.endswith(".gz")
            and path.name != "piano-samples.bin"]


def generate(data, output):
    entries = assets(data)
    lines = ["// Generated by tools/embed_web.py. Edit files in data/ instead.",
             "#pragma once", "#include <Arduino.h>", "#include <cstring>",
             "namespace EmbeddedWeb {",
             "struct Asset { const char* path; const uint8_t* data; size_t size; };"]
    for index, (_, content) in enumerate(entries):
        lines.append(f"static const uint8_t asset{index}[] PROGMEM = {{")
        lines.extend(",".join(str(b) for b in content[start:start + 32]) + ","
                     for start in range(0, len(content), 32))
        lines.append("};")
    lines.append("static const Asset files[] = {")
    for index, (path, _) in enumerate(entries):
        lines.append(f'{{"{path}", asset{index}, sizeof(asset{index})}},')
    lines.extend(["};", "inline const Asset* find(const char* path) {",
                  "for (const auto& asset : files) if (strcmp(asset.path, path) == 0) return &asset;",
                  "return nullptr;", "}", "} // namespace EmbeddedWeb", ""])
    content = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != content:
        output.write_text(content, encoding="utf-8")
    return entries
